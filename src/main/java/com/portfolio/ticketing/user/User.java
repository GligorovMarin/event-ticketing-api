package com.portfolio.ticketing.user;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import org.hibernate.annotations.CreationTimestamp;

import java.time.Instant;
import java.util.UUID;

/**
 * A row of the {@code users} table (created by migration V1__create_users.sql).
 *
 * <p>An <b>entity</b> is a Java class that Hibernate (JPA) maps onto a table: each field is a column, each
 * instance a row. Hibernate is set to {@code ddl-auto: validate} (application.yml), so at startup it checks
 * that this class matches the table and refuses to start if they drift apart. Only Flyway changes the schema.
 *
 * <p>Deliberately plain Java (no Lombok): the code you read is the code that runs.
 *
 * <p>Used by: {@link UserRepository}, auth/AuthService.
 */
@Entity
@Table(name = "users")
public class User {

    // Generated by the application (not the database), so the id exists before the INSERT.
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @Column(nullable = false, unique = true, length = 255)
    private String email;

    @Column(name = "full_name", nullable = false, length = 100)
    private String fullName;

    // A bcrypt hash. The real password is never stored and never leaves the auth package.
    @Column(name = "password_hash", nullable = false, length = 100)
    private String passwordHash;

    // EnumType.STRING stores the NAME ("CUSTOMER"). The alternative, ORDINAL, stores 0/1/2 and silently
    // changes meaning if someone reorders the enum constants. Always use STRING.
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private UserRole role;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    /** Required by JPA (Hibernate creates instances through it). Not for application code. */
    protected User() {
    }

    public User(String email, String fullName, String passwordHash, UserRole role) {
        this.email = email;
        this.fullName = fullName;
        this.passwordHash = passwordHash;
        this.role = role;
    }

    public UUID getId() {
        return id;
    }

    public String getEmail() {
        return email;
    }

    public String getFullName() {
        return fullName;
    }

    public String getPasswordHash() {
        return passwordHash;
    }

    public UserRole getRole() {
        return role;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }
}
