package com.portfolio.ticketing.event;

import com.portfolio.ticketing.common.ConflictException;
import com.portfolio.ticketing.common.NotFoundException;
import com.portfolio.ticketing.common.PageResponse;
import com.portfolio.ticketing.event.dto.CreateEventRequest;
import com.portfolio.ticketing.event.dto.CreateSectionRequest;
import com.portfolio.ticketing.event.dto.EventDetailResponse;
import com.portfolio.ticketing.event.dto.EventSummaryResponse;
import com.portfolio.ticketing.event.dto.SectionResponse;
import com.portfolio.ticketing.security.AuthenticatedUser;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageRequest;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.Clock;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;

/**
 * Everything about events and their seat maps: the rules live HERE, not in the controllers.
 *
 * <p>Connections: called by {@link EventController} (public browsing + organizer writes) and
 * {@link OrganizerEventController}; stores through {@link EventRepository} / {@link SectionRepository};
 * seats are generated by {@link SeatMapService}; "now" comes from the injected {@link Clock}.
 *
 * <p>Ownership rule used throughout: an event that exists but belongs to ANOTHER organizer looks exactly like
 * an event that does not exist (404, not 403). Answering 403 would confirm to a stranger that the id is real.
 */
@Service
public class EventService {

    private final EventRepository events;
    private final SectionRepository sections;
    private final SeatMapService seatMap;
    private final Clock clock;

    public EventService(EventRepository events, SectionRepository sections, SeatMapService seatMap, Clock clock) {
        this.events = events;
        this.sections = sections;
        this.seatMap = seatMap;
        this.clock = clock;
    }

    // ---- Organizer: building an event -----------------------------------------------------------

    @Transactional
    public EventDetailResponse create(AuthenticatedUser organizer, CreateEventRequest request) {
        Event event = events.save(new Event(
                organizer.id(), request.name(), request.description(), request.venue(), request.startsAt()));

        return EventDetailResponse.from(event, List.of());
    }

    /**
     * Adds a priced block of seats to a DRAFT event and generates its seats.
     *
     * <p>The event row is locked first ({@code FOR UPDATE}, see EventRepository.findOwnedForUpdate), so
     * concurrent organizer writes on the same event take turns. Section and seats are saved in ONE
     * transaction: either the section exists with all its seats, or nothing was created.
     */
    @Transactional
    public SectionResponse addSection(AuthenticatedUser organizer, UUID eventId, CreateSectionRequest request) {
        Event event = events.findOwnedForUpdate(eventId, organizer.id())
                .orElseThrow(() -> new NotFoundException("Event " + eventId + " not found"));

        if (event.getStatus() != EventStatus.DRAFT) {
            // The seat map is frozen once on sale: seats must not appear or vanish under customers' feet.
            throw new ConflictException("Sections can only be added while the event is a draft");
        }

        long planned = sections.countPlannedSeats(eventId);
        long requested = (long) request.rows() * request.seatsPerRow();
        if (planned + requested > SeatMapLayout.MAX_SEATS_PER_EVENT) {
            throw new ConflictException("An event can have at most " + SeatMapLayout.MAX_SEATS_PER_EVENT
                    + " seats; this event already has " + planned);
        }

        Section section;
        try {
            // saveAndFlush sends the INSERT now, so a duplicate name is detected inside this try block.
            section = sections.saveAndFlush(new Section(
                    eventId, request.name(), request.priceCents(), request.rows(), request.seatsPerRow()));
        } catch (DataIntegrityViolationException duplicateName) {
            // The database's UNIQUE (event_id, name) decides, not a check-then-insert.
            throw new ConflictException("This event already has a section named \"" + request.name() + "\"");
        }

        seatMap.generateSeats(section);
        return SectionResponse.from(section);
    }

    /** DRAFT -> PUBLISHED. From now on the event is public and the seat map is frozen. */
    @Transactional
    public EventDetailResponse publish(AuthenticatedUser organizer, UUID eventId) {
        Event event = events.findOwnedForUpdate(eventId, organizer.id())
                .orElseThrow(() -> new NotFoundException("Event " + eventId + " not found"));

        if (event.getStatus() != EventStatus.DRAFT) {
            throw new ConflictException("Only a draft event can be published (this one is " + event.getStatus() + ")");
        }
        if (!sections.existsByEventId(eventId)) {
            throw new ConflictException("Add at least one section before publishing");
        }
        if (!event.getStartsAt().isAfter(clock.instant())) {
            throw new ConflictException("The event's start time has already passed");
        }

        event.publish();
        return detail(event);
    }

    // ---- Organizer: looking at their own events ---------------------------------------------------

    @Transactional(readOnly = true)
    public List<EventSummaryResponse> listMine(AuthenticatedUser organizer) {
        List<Event> mine = events.findByOrganizerIdOrderByStartsAtDesc(organizer.id());

        return summaries(mine);
    }

    @Transactional(readOnly = true)
    public EventDetailResponse getMine(AuthenticatedUser organizer, UUID eventId) {
        Event event = events.findByIdAndOrganizerId(eventId, organizer.id())
                .orElseThrow(() -> new NotFoundException("Event " + eventId + " not found"));

        return detail(event);
    }

    // ---- Public: browsing ---------------------------------------------------------------------------

    /** Published events that have not started yet, soonest first, optionally filtered by a name fragment. */
    @Transactional(readOnly = true)
    public PageResponse<EventSummaryResponse> listPublic(String nameQuery, int page, int size) {
        PageRequest pageRequest = PageRequest.of(page, size);
        String pattern = escapeLikePattern(nameQuery);

        // No search text: the plain listing. Search text: the filtered listing (see the repository for why two queries).
        Page<Event> found = pattern == null
                ? events.findUpcomingPublished(clock.instant(), pageRequest)
                : events.searchUpcomingPublished(clock.instant(), pattern, pageRequest);

        List<EventSummaryResponse> items = summaries(found.getContent());
        return new PageResponse<>(items, found.getNumber(), found.getSize(), found.getTotalElements(), found.getTotalPages());
    }

    @Transactional(readOnly = true)
    public EventDetailResponse getPublic(UUID eventId) {
        // A draft or cancelled event is "not found" for the public.
        Event event = events.findByIdAndStatus(eventId, EventStatus.PUBLISHED)
                .orElseThrow(() -> new NotFoundException("Event " + eventId + " not found"));

        return detail(event);
    }

    // ---- Helpers ------------------------------------------------------------------------------------

    private EventDetailResponse detail(Event event) {
        return EventDetailResponse.from(event, sections.findByEventIdOrderByName(event.getId()));
    }

    /**
     * Converts events into list lines, adding each event's cheapest price with ONE extra query for the whole
     * list (not one per event: that would be the "N+1 queries" problem).
     */
    private List<EventSummaryResponse> summaries(List<Event> eventList) {
        if (eventList.isEmpty()) {
            return List.of();
        }

        List<UUID> ids = eventList.stream().map(Event::getId).toList();

        // A HashMap from event id to price: each lookup below is O(1), however long the list.
        Map<UUID, Integer> cheapestByEvent = new HashMap<>();
        for (SectionRepository.EventPrice price : sections.findCheapestPrices(ids)) {
            cheapestByEvent.put(price.getEventId(), price.getMinPriceCents());
        }

        return eventList.stream()
                .map(event -> EventSummaryResponse.from(event, cheapestByEvent.get(event.getId())))
                .toList();
    }

    /**
     * In a LIKE pattern, % and _ are wildcards and the backslash is our escape character. A user searching for
     * "50%" must find "50%", not "50 anything", so those three characters are escaped. Null/blank means "no filter".
     */
    static String escapeLikePattern(String text) {
        if (text == null || text.isBlank()) {
            return null;
        }
        return text.trim().replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_");
    }
}
